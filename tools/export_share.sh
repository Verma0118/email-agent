#!/bin/bash
# Build a copy of email-agent safe to give a friend.
# Strips profile.json, personal/, _old/, local notes, caches; then scans the copy for
# anything from the owner's profile (name, email, phone, handles, orgs) or
# personal/share_blocklist.txt, and refuses
# to zip if a leak is found.
# Usage: tools/export_share.sh [DEST_DIR]   (default ~/Desktop/email-agent-share)
set -euo pipefail
SKILL="$(cd "$(dirname "$0")/.." && pwd)"
DEST="${1:-$HOME/Desktop/email-agent-share}"
OUT="$DEST/email-agent"

if [ -e "$DEST" ] && [ ! -f "$DEST/.email-agent-share" ]; then
  echo "refusing: $DEST exists and was not made by this script"; exit 1
fi
rm -rf "$OUT" "$DEST/email-agent.zip"
mkdir -p "$OUT"; touch "$DEST/.email-agent-share"

rsync -a \
  --exclude 'profile.json' --exclude 'personal/' --exclude '_old/' \
  --exclude 'CLAUDE.local.md' --exclude '__pycache__/' --exclude '*.pyc' --exclude '.DS_Store' \
  "$SKILL/" "$OUT/"
rm -f "$OUT"/tests/fixtures/fail__*.txt   # regenerated by run_tests.sh

# Leak scan: every identifying value in the owner's profile + known private terms.
TERMS=$(python3 - "$SKILL/profile.json" <<'PY'
import json, re, sys
from pathlib import Path
p = Path(sys.argv[1])
terms = set()
block = p.parent / "personal" / "share_blocklist.txt"   # extra private terms, one per line
if block.exists():
    terms.update(l.strip() for l in block.read_text().splitlines() if l.strip())
if p.exists():
    d = json.loads(p.read_text())
    for k in ("name", "sending_email", "phone", "portfolio_display", "linkedin_display", "school", "school_short"):
        if d.get(k): terms.add(d[k])
    terms.update(d.get("name", "").split())
    if d.get("calendar_id", "primary") != "primary": terms.add(d["calendar_id"])
    for inv in d.get("involvements", []):
        terms.add(inv["org"])
print("\n".join(sorted(t for t in terms if len(t) > 2)))
PY
)
leaks=0
while IFS= read -r term; do
  # The repo's own GitHub URL (github.com/<owner>/email-agent) is public and allowed.
  hits=$(grep -rIi -F -- "$term" "$OUT" | grep -vE 'github(usercontent)?\.com/[A-Za-z0-9_-]+/email-agent' | cut -d: -f1 | sort -u || true)
  if [ -n "$hits" ]; then
    leaks=1; echo "LEAK: '$term' in:"; echo "$hits" | sed "s|$OUT/|    |"
  fi
done <<< "$TERMS"
if [ $leaks -ne 0 ]; then
  echo "Export stopped: remove the leaks above (or move them into personal/), then rerun."; exit 1
fi

"$OUT/tests/run_tests.sh" >/dev/null && echo "tests: pass" || { echo "tests failed in the export"; exit 1; }
rm -f "$OUT"/tests/fixtures/fail__*.txt
(cd "$DEST" && zip -qr email-agent.zip email-agent)
echo "clean export: $OUT"
echo "zip:          $DEST/email-agent.zip"
